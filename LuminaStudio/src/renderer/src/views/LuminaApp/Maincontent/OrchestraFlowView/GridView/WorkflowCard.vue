  if (!buttonEl) return

  const rect = buttonEl.getBoundingClientRect()
  const menuWidth = 128

  menuPosition.value = {
    top: rect.bottom + window.scrollY + 4,
    left: rect.right + window.scrollX - menuWidth
  }
}

function toggleMenu() {
  if (!showMenu.value) {
